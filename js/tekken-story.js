  E.tkVisibleChapters = function (s) {
    const t = E.tkEnsure(s);
    const side = (t.flags && t.flags.tk_side) || '';
    const hasR = !!(t.flags && t.flags.tk_reina);
    return D.TK_CH.filter((c) => {
      if (c.needReina && !hasR) return false;
      if (c.skipReina && hasR) return false;
      if (c.route === 'self' && !hasR) return false;
      if (c.route && side && c.route !== side) return false;
      if (c.route && !side) return false;
      return true;
    });
  };

  D.TK_CH.forEach((c, i) => {
    const sc = D.TK_SCENES[c.id] || {};
    c.n = c.n || sc.t;
    c.i = i;
  });
  D.TK_CH_MAP = {};
  D.TK_CH.forEach((c) => { D.TK_CH_MAP[c.id] = c; });

  E.tkChapterOpen = function (s, id) {
    const t = E.tkEnsure(s);
    if (t.story.includes(id)) return true;
    const vis = E.tkVisibleChapters(s);
    const i = vis.findIndex((c) => c.id === id);
    if (i < 0) return false;
    const ch = vis[i];
    if (ch.need != null && t.best < ch.need && t.stage < ch.need && t.won.length < ch.need) return false;
    if (i === 0) return true;
    const prev = vis[i - 1];
    if (prev && !t.story.includes(prev.id)) return false;
    if (ch.route && t.flags.tk_side !== ch.route) return false;
    if (ch.choice && vis[i - 1] && vis[i - 1].choice && !t.flags.tk_side) return false;
    return true;
  };

  E.tkFinishChapter = function (s, id) {
    const t = E.tkEnsure(s); if (t.story.includes(id)) return '';
    if (!E.tkChapterOpen(s, id)) return 'Сначала предыдущая глава';
    const ch = D.TK_CH_MAP[id]; if (!ch) return 'Нет такой главы';
    if (ch.choice && !t.flags.tk_side) return 'Сначала сделайте выбор';
    if (ch.pick === 'ally' && !t.ally) return 'Сначала выберите союзника';
    if (ch.vow && !t.vowDone) return 'Сначала сделайте выбор';
    if (ch.ending) {
      t.ending = ch.ending || t.flags.tk_side || 'neutral';
      E.tkGrantEnding(s, t.ending);
    }
    if (ch.blood && t.flags.tk_blood) E.tkGiveBlood(s, 1);
    t.story.push(id); s.rev = (s.rev || 0) + 1; return '';
  };

  E.tkSceneLines = function (s, sc) {
    if (sc && typeof sc.linesFor === 'function') return sc.linesFor(s);
    return (sc && sc.lines) || [];
  };

